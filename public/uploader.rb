require "base64"
require "json"
require "net/http"
require "optparse"
require "pathname"
require "uri"

LCOV_DEPRECATION_NOTICE = "⚠️ The LCOV coverage format is being deprecated and will be removed from " \
                          "the UndercoverCI uploader and APIs after 2026/01/31. Please migrate to " \
                          "SimpleCov::Formatter::Undercover: " \
                          "https://undercover-ci.com/docs#reporting"

# Environment variables that identify a pull request build, mapped to the number within them
PULL_REQUEST_ENV_VARS = {
  "GITHUB_REF" => /\Arefs\/pull\/(\d+)\//, # GitHub Actions
  "CIRCLE_PULL_REQUEST" => /\/pull\/(\d+)\z/, # CircleCI
  "CI_MERGE_REQUEST_IID" => /\A(\d+)\z/ # GitLab CI
}.freeze

Options = Struct.new(:commit, :lcov, :simplecov, :repo, :url, :cancel, :pull_request) do
  def valid?
    commit && !commit.empty? &&
      repo && !repo.empty? &&
      ((lcov && !lcov.empty?) || (simplecov && !simplecov.empty?))
  end

  def pull_request_valid?
    pull_request.nil? || pull_request.match?(/\A\d+\z/)
  end

  def detected_pull_request_number
    PULL_REQUEST_ENV_VARS.each do |name, pattern|
      match = ENV.fetch(name, nil).to_s.match(pattern)
      return match[1] if match
    end
    nil
  end

  # Missing --pull-request is only a problem on a pull request build, where it is the
  # difference between a check on a fork's pull request and no check at all
  def pull_request_warning
    number = detected_pull_request_number
    return if pull_request || number.nil?

    "⚠️ This looks like a build of pull request ##{number}, but --pull-request was not set. " \
      "Pull requests opened from forks need it to report coverage, e.g. --pull-request #{number}. " \
      "See https://undercover-ci.com/docs#configuration"
  end
end

class UndercoverCiCoverageUpload
  attr_reader :exitcode, :options

  def initialize(argv = ARGV)
    @exitcode = 0
    @options = Options.new
    @opts_parser = OptionParser.new do |opts|
      opts.banner = "Usage: ruby -e \"$(curl -s https://undercover-ci.com/uploader.rb)\" -- [options]"

      opts.on("--repo REPO", "Repository name") do |v|
        @options.repo = v
      end
      opts.on("--commit COMMIT", "Commit SHA") do |v|
        @options.commit = v
      end
      # optional argument, so a CI template that expands to nothing (a push build) is not an error
      opts.on("--pull-request [NUMBER]", "Pull request number, required for pull requests from forks") do |v|
        value = v.to_s.strip
        @options.pull_request = value.empty? ? nil : value
      end
      opts.on("--cancel", "Cancel coverage check") do |v|
        @options.cancel = v
      end
      opts.on("--simplecov SIMPLECOV_JSON_FILE", "Coverage file generated by SimplCov::Formatter::Undercover") do |v|
        @options.simplecov = v
      end
      opts.on("--lcov LCOV_FILE", "LCOV file path") do |v|
        @options.lcov = v
      end
      opts.on("--url URL", "Custom UndercoverCI URL") do |v|
        @options.url = URI(v)
      end
    end
    @opts_parser.parse!(argv)
    @options.url ||= URI("https://undercover-ci.com/v1/coverage")
  end

  def valid?
    return true if @options.valid?

    error(@opts_parser)
    false
  end

  def upload
    unless @options.valid?
      error(@opts_parser)
      return self
    end

    unless @options.pull_request_valid?
      error("--pull-request must be a number, got #{@options.pull_request.inspect}")
      return self
    end

    warning = @options.pull_request_warning
    warn(warning) if warning

    puts LCOV_DEPRECATION_NOTICE if @options.lcov

    file = @options.simplecov || @options.lcov
    data = File.read(file)

    unless data.size.positive?
      error("#{file} is an empty file, is that the correct path?")
      return self
    end

    coverage_data_base64 = Base64.strict_encode64(data)
    request(
      Net::HTTP::Post,
      @options.url,
      {
        repo: @options.repo,
        sha: @options.commit,
        file_base64: coverage_data_base64,
        file_type: @options.lcov ? :lcov : :json,
        pull_request_number: @options.pull_request
      }.compact.to_json
    )
  end

  def cancel
    request(
      Net::HTTP::Delete,
      @options.url,
      {
        repo: @options.repo,
        sha: @options.commit
      }.to_json
    )
  end

  private

  def request(method, url, body)
    http = Net::HTTP.start(url.hostname, use_ssl: url.instance_of?(URI::HTTPS))
    req = method.new(url.path, "Content-Type" => "application/json")
    req.body = body
    resp = http.request(req)
    case resp.code.to_i
    when (200..299)
      puts("Done! #{resp.code}")
    when 404
      error "Error 404: does a check for commit #{@options.commit} exist in #{@options.repo}? " \
            "Visit https://undercover-ci.com/docs or get support at help@undercover-ci.com."
    else
      error "Error #{resp.code}, #{resp.body}. " \
            "Visit https://undercover-ci.com/docs or get support at help@undercover-ci.com."
    end
    self
  end

  def error(message)
    @exitcode = 1
    warn(message)
  end
end

if __FILE__ == $PROGRAM_NAME
  uploader = UndercoverCiCoverageUpload.new
  exit(uploader.exitcode) unless uploader.valid?
  if uploader.options.cancel
    uploader.cancel
  else
    uploader.upload
  end
  exit(uploader.exitcode)
end
